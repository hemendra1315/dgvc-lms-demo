import manifest from './generated/pyq-resources.json';
import type { DemoState, PyqResource } from './types';

/**
 * Initial demo state. Resources come from the generated PYQ manifest
 * (scripts/pyq/generate_pyq_papers.py), so every record points at a real PDF in
 * public/demo-pdfs/. Changing the manifest changes SEED_VERSION, which makes
 * browsers with older stored demo data reseed automatically.
 */
export const SEED_RESOURCES = manifest.resources as PyqResource[];
export const SEED_VERSION = `pyq-${manifest.seed}-${manifest.count}-${SEED_RESOURCES.reduce((n, r) => n + r.file_size, 0)}`;

export function initialState(): DemoState {
  return {
    version: SEED_VERSION,
    resources: SEED_RESOURCES.map((r) => ({ ...r })),
    bookmarks: {},
    downloads: {},
    recent: {},
    audit: [
      {
        id: 'seed',
        at: new Date().toISOString(),
        actor: 'System (demo seed)',
        action: 'Seeded sample question papers',
        entity: `${SEED_RESOURCES.length} resources`,
        detail: 'Generated by scripts/pyq/generate_pyq_papers.py',
      },
    ],
    sessionUserId: null,
  };
}
